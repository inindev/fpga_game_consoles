#!/usr/bin/env python3
"""Recreate the imported upstream files of retro-fpga, then apply our patches.

Every imported file is listed in manifest.tsv with the upstream repo, the exact
commit and the original path. This script copies each one to its new place
(straight from git, no checkout needed), applies patches/*.patch in name order,
and writes SOURCES.md.

    python3 tools/import/assemble.py --nestang ~/src/nestang --snestang ~/src/snestang

Options:
    --out DIR       write the tree somewhere else (default: the repo root)
    --no-patches    copy the upstream files only
    --sources-only  only regenerate SOURCES.md
"""
import argparse
import collections
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
UPSTREAM_URL = {
    "nestang": "https://github.com/nand2mario/nestang",
    "snestang": "https://github.com/nand2mario/snestang",
}


def read_manifest():
    rows = []
    with open(os.path.join(HERE, "manifest.tsv")) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            dest, repo, commit, src, note = (line.rstrip("\n").split("\t") + [""])[:5]
            rows.append((dest, repo, commit, src, note))
    return rows


def patches():
    d = os.path.join(HERE, "patches")
    return sorted(os.path.join(d, p) for p in os.listdir(d) if p.endswith(".patch"))


def patched_files():
    """Map file -> [(patch name, first comment line of the patch)]."""
    touched = collections.defaultdict(list)
    for p in patches():
        with open(p) as f:
            text = f.read()
        why = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), "")
        for line in text.splitlines():
            if line.startswith("+++ "):
                path = line[4:].split("\t")[0]
                path = path[2:] if path.startswith("b/") else path
                touched[path].append((os.path.basename(p), why))
    return touched


def write_sources(rows, out):
    touched = patched_files()
    repos = sorted({(r[1], r[2]) for r in rows})
    lines = [
        "# Sources",
        "",
        "Generated by `tools/import/assemble.py` from `tools/import/manifest.tsv`. Do not edit by hand.",
        "",
        "Every file below was imported from one of these upstream snapshots:",
        "",
        "| Upstream | Commit |",
        "|---|---|",
    ]
    lines += [f"| [{r}]({UPSTREAM_URL[r]}) | `{c}` |" for r, c in repos]
    lines += [
        "",
        "Files are renamed (lowercase) and moved; their content is unchanged unless the",
        "**Modified** column names a patch in `tools/import/patches/`. Files not listed here",
        "were written for retro-fpga.",
        "",
    ]
    by_area = collections.defaultdict(list)
    for r in sorted(rows):
        by_area[r[0].split("/")[0]].append(r)
    for area in sorted(by_area):
        lines += [f"## {area}/", "", "| File | Upstream | Original path | Notes | Modified |", "|---|---|---|---|---|"]
        for dest, repo, commit, src, note in by_area[area]:
            mods = "<br>".join(f"`{p}`" for p, _ in touched.get(dest, [])) or ""
            lines.append(f"| `{dest}` | {repo} `{commit[:7]}` | `{src}` | {note} | {mods} |")
        lines.append("")
    if touched:
        lines += ["## Modifications", ""]
        for path in sorted(touched):
            for p, why in touched[path]:
                lines.append(f"- `{path}`: `{p}`: {why}")
        lines.append("")
    with open(os.path.join(out, "SOURCES.md"), "w") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--nestang")
    ap.add_argument("--snestang")
    ap.add_argument("--out", default=ROOT)
    ap.add_argument("--no-patches", action="store_true")
    ap.add_argument("--sources-only", action="store_true")
    a = ap.parse_args()
    rows = read_manifest()
    if not a.sources_only:
        clones = {"nestang": a.nestang, "snestang": a.snestang}
        if not all(clones.values()):
            sys.exit("need --nestang and --snestang (local clones of the upstream repos)")
        for dest, repo, commit, src, _ in rows:
            data = subprocess.run(["git", "-C", clones[repo], "show", f"{commit}:{src}"],
                                  capture_output=True, check=True).stdout
            path = os.path.join(a.out, dest)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(data)
        print(f"copied {len(rows)} files")
        if not a.no_patches:
            for p in patches():
                subprocess.run(["patch", "-s", "-p1", "--forward", "-d", a.out, "-i", p], check=True)
                print("applied", os.path.basename(p))
    write_sources(rows, a.out)
    print("wrote SOURCES.md")


if __name__ == "__main__":
    main()
